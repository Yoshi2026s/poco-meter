export const CONTACT_SESSION_SECONDS = 31536000;
const LIFETIME = CONTACT_SESSION_SECONDS * 1000;
export class ContactSessionError extends Error {
  constructor() {
    super('お問い合わせの利用期限が切れたか、アクセスが停止されました。入力内容を残して、お問い合わせを開き直してください。');
    this.status = 401;
  }
}
function validSession(row, now) {
  return row && row.revoked_at == null && Number.isSafeInteger(row.created_at) && Number.isSafeInteger(row.expires_at)
    && row.created_at <= now && row.expires_at > now && row.expires_at <= row.created_at + LIFETIME;
}
async function session(db, hash) {
  return db.prepare('SELECT created_at,expires_at,revoked_at FROM contact_sessions WHERE visitor_hash=?').bind(hash).first();
}
export async function assertContactSession(db, hash, now = Date.now()) {
  if (!validSession(await session(db, hash), now)) throw new ContactSessionError();
}
// Tokens are generated by the server, before this function is called. Never issue
// a session for an arbitrary cookie supplied by the caller.
export async function createContactSession(db, hash, now = Date.now()) {
  await db.prepare('INSERT OR IGNORE INTO contact_sessions (visitor_hash,created_at,expires_at,revoked_at) VALUES (?,?,?,NULL)').bind(hash, now, now + LIFETIME).run();
  await assertContactSession(db, hash, now);
}
export async function requireContactSession(db, hash, beforeAdopt, now = Date.now()) {
  const current = await session(db, hash);
  if (current) {
    if (!validSession(current, now)) throw new ContactSessionError();
    return;
  }
  // Preserve legacy history only when this capability already owns a thread.
  // Use its earliest known use, never a sliding expiry from each new request.
  const legacy = await db.prepare('SELECT MIN(created_at) AS created_at FROM contact_threads WHERE visitor_hash=?').bind(hash).first();
  if (!Number.isSafeInteger(legacy?.created_at) || legacy.created_at > now || legacy.created_at + LIFETIME <= now) throw new ContactSessionError();
  await beforeAdopt();
  await db.prepare('INSERT OR IGNORE INTO contact_sessions (visitor_hash,created_at,expires_at,revoked_at) VALUES (?,?,?,NULL)').bind(hash, legacy.created_at, legacy.created_at + LIFETIME).run();
  // A concurrent owner revocation wins over adoption; never overwrite a tombstone.
  await assertContactSession(db, hash, Date.now());
}
export async function revokeContactSession(db, threadId, now = Date.now()) {
  const thread = await db.prepare('SELECT visitor_hash FROM contact_threads WHERE id=?').bind(threadId).first();
  if (!thread) return false;
  let writeError;
  try {
    await db.prepare(`INSERT INTO contact_sessions (visitor_hash,created_at,expires_at,revoked_at)
      SELECT visitor_hash,MIN(created_at),MIN(created_at)+?,? FROM contact_threads WHERE visitor_hash=? GROUP BY visitor_hash
      ON CONFLICT(visitor_hash) DO UPDATE SET revoked_at=COALESCE(contact_sessions.revoked_at,excluded.revoked_at)`).bind(LIFETIME, now, thread.visitor_hash).run();
  } catch (error) { writeError = error; }
  // A lost write response is recoverable when the persisted revocation is visible.
  const saved = await session(db, thread.visitor_hash);
  if (saved?.revoked_at != null) return true;
  throw writeError || new Error('Session revocation not confirmed');
}
